"""Export a four-section, south-facing Java block with one shared atlas."""
from PIL import Image, ImageDraw, ImageFont
import base64, io, json, uuid
import numpy as np
from workbench_model import native_rotation, transform, write, render

PARTS=[('front_left',0,16),('front_right',16,16),('back_left',0,0),('back_right',16,0)]
TURNS={'south':0,'west':90,'north':180,'east':270}

def element(e,sx,sz,tw,th):
    result=dict(name=e['name'],**{'from':[e['from'][0]-sx,e['from'][1],e['from'][2]-sz],
        'to':[e['to'][0]-sx,e['to'][1],e['to'][2]-sz]},faces={
        f:dict(uv=[v*16/(tw if i%2==0 else th) for i,v in enumerate(data['uv'])],texture='#0')
        for f,data in e['faces'].items()})
    r=native_rotation(e)
    if r:
        r['origin']=r['origin'].copy();r['origin'][0]-=sx;r['origin'][2]-=sz;result['rotation']=r
    return result

def export(here,root,elements,atlas,boxes):
    ident='smelter';assets=root/'src/main/resources/assets/archecraft';tw,th=atlas.size
    textures={'0':'archecraft:block/smelter','particle':'archecraft:block/smelter'}
    sections=[[] for _ in PARTS]
    for e in elements:
        lo,hi=e['from'],e['to'];r=native_rotation(e)
        points=np.array([transform([x,y,z],r) for x in (lo[0],hi[0]) for y in (lo[1],hi[1]) for z in (lo[2],hi[2])])
        assert points.min()>=0 and points.max()<=32,e['name']
        for i,(part,sx,sz) in enumerate(PARTS):
            a=[max(lo[0],sx),lo[1],max(lo[2],sz)];b=[min(hi[0],sx+16),hi[1],min(hi[2],sz+16)]
            if a[0]>=b[0] or a[2]>=b[2]:continue
            for axis in [0,2]:
                if r and r['axis']!='xyz'[axis]:
                    assert a[axis]==lo[axis] and b[axis]==hi[axis],'Cannot split rotated cube: '+e['name']
            cut=json.loads(json.dumps(e));cut['from']=a;cut['to']=b
            for face in cut['faces']:
                old=e['faces'][face]['uv'];uv=cut['faces'][face]['uv']
                ui=2 if face in ('east','west') else 0
                offset=(hi[ui]-b[ui]) if face in ('north','east') else a[ui]-lo[ui]
                density=(old[2]-old[0])/(hi[ui]-lo[ui])
                uv[0]=old[0]+offset*density;uv[2]=uv[0]+(b[ui]-a[ui])*density
                if face in ('up','down'):
                    density=(old[3]-old[1])/(hi[2]-lo[2])
                    offset=hi[2]-b[2] if face=='down' else a[2]-lo[2]
                    uv[1]=old[1]+offset*density;uv[3]=uv[1]+(b[2]-a[2])*density
            sections[i].append(element(cut,sx,sz,tw,th))
    for i,(part,_,_) in enumerate(PARTS):
        write(assets/f'models/block/smelter_{part}.json',dict(parent='minecraft:block/block',textures=textures,elements=sections[i]))
    write(assets/'blockstates/smelter.json',dict(variants={
        f'facing={facing},part={part}':dict(model='archecraft:block/smelter_'+part,y=angle)
        for facing,angle in TURNS.items() for part,_,_ in PARTS}))
    display={
        'gui':dict(rotation=[25,225,0],translation=[0,-1,0],scale=[0.34]*3),
        'ground':dict(rotation=[0,0,0],translation=[0,3,0],scale=[0.18]*3),
        'fixed':dict(rotation=[0,0,0],translation=[0,0,0],scale=[0.3]*3),
        'thirdperson_righthand':dict(rotation=[75,45,0],translation=[0,2.5,0],scale=[0.25]*3),
        'firstperson_righthand':dict(rotation=[0,45,0],translation=[0,0,0],scale=[0.3]*3)}
    write(assets/'models/item/smelter.json',dict(parent='minecraft:block/block',textures=textures,
        elements=[element(e,8,8,tw,th) for e in elements],display=display))
    atlas.save(assets/'textures/block/smelter.png');atlas.save(here/'smelter.png')
    png=io.BytesIO();atlas.save(png,format='PNG')
    groups=[dict(name=g,origin=[16,0,16],uuid=str(uuid.uuid5(uuid.NAMESPACE_URL,ident+'/'+g)),
        children=[e['uuid'] for e in elements if e['_group']==g]) for g in dict.fromkeys(e['_group'] for e in elements)]
    write(here/'smelter.bbmodel',dict(meta=dict(format_version='4.10',model_format='java_block',box_uv=False),name=ident,
        resolution=dict(width=tw,height=th),elements=[{k:v for k,v in e.items() if not k.startswith('_')} for e in elements],
        outliner=groups,display=display,textures=[dict(name='smelter.png',uuid=str(uuid.uuid5(uuid.NAMESPACE_URL,ident+'/texture')),
        id='0',namespace='archecraft',folder='block',width=tw,height=th,uv_width=tw,uv_height=th,mode='bitmap',saved=True,
        source='data:image/png;base64,'+base64.b64encode(png.getvalue()).decode())]))
    lines=['package com.redcookies.archecraft.workbench;','','import net.minecraft.core.Direction;',
        'import net.minecraft.world.level.block.Block;','import net.minecraft.world.phys.shapes.Shapes;',
        'import net.minecraft.world.phys.shapes.VoxelShape;','',
        '// Generated by art/models/smelter/build_model.py. Keep targeting shapes simple.',
        'final class SmelterShapes {','    static VoxelShape[][] create() {','        VoxelShape[][] shapes=new VoxelShape[4][4];',
        '        double[][][] boxes={']
    for section in boxes:
        assert len(section)<=4
        lines.append('            {')
        for b in section:
            assert 0<=b[0]<b[3]<=16 and 0<=b[2]<b[5]<=16 and 0<=b[1]<b[4]<=32
            lines.append('                {'+', '.join(str(v) for v in b)+'},')
        lines.append('            },')
    lines+=['        };','        for (int part=0;part<4;part++) {',
        '            for (Direction facing : Direction.Plane.HORIZONTAL) {','                VoxelShape shape=Shapes.empty();',
        '                for (double[] box : boxes[part]) {','                    double x0=box[0],z0=box[2],x1=box[3],z1=box[5];',
        '                    int turns=switch(facing) {case WEST -> 1;case NORTH -> 2;case EAST -> 3;default -> 0;};',
        '                    for (int turn=0;turn<turns;turn++) {','                        double nx0=16-z1,nz0=x0,nx1=16-z0,nz1=x1;',
        '                        x0=nx0;z0=nz0;x1=nx1;z1=nz1;','                    }',
        '                    shape=Shapes.or(shape,Block.box(x0,box[1],z0,x1,box[4],z1));','                }',
        '                shapes[part][facing.get2DDataValue()]=shape.optimize();','            }','        }','        return shapes;','    }','}']
    (root/'src/main/java/com/redcookies/archecraft/workbench/SmelterShapes.java').write_text('\n'.join(lines)+'\n')
    preview=Image.new('RGB',(1400,655),(27,33,38))
    preview.paste(render(elements,atlas,32,center=(16,0,16),scale=13,baseline=440),(0,45))
    preview.paste(render(elements,atlas,212,center=(16,0,16),scale=13,baseline=440),(700,45))
    d=ImageDraw.Draw(preview);font=ImageFont.truetype('C:/Windows/Fonts/segoeuib.ttf',25)
    small=ImageFont.truetype('C:/Windows/Fonts/segoeui.ttf',16)
    d.text((30,15),'SMELTER / 2 x 2 BLOCK FOOTPRINT',font=font,fill=(226,226,215))
    d.text((30,620),'FRONT / 3-QUARTER',font=small,fill=(167,180,186))
    d.text((730,620),'REVERSE / 3-QUARTER',font=small,fill=(167,180,186))
    preview.save(here/'smelter_preview.png')
    print(f'Exported {len(elements)} cuboids, four sections, editable project, {sum(map(len,boxes))} gameplay boxes.')
