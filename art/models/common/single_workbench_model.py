"""Export a one-space cuboid workbench and its inexpensive targeting shapes."""
from PIL import Image, ImageDraw, ImageFont
import base64, io, uuid
import numpy as np
from workbench_model import java_element, native_rotation, transform, write, render

def export(here,root,ident,shape_class,elements,atlas,boxes,title):
    assets=root/'src/main/resources/assets/archecraft';tw,th=atlas.size
    textures={'0':'archecraft:block/'+ident,'particle':'archecraft:block/'+ident}
    for e in elements:
        points=np.array([transform([x,y,z],native_rotation(e)) for x in (e['from'][0],e['to'][0])
            for y in (e['from'][1],e['to'][1]) for z in (e['from'][2],e['to'][2])])
        assert points.min()>=0 and points[:,0].max()<=16 and points[:,2].max()<=16 and points[:,1].max()<=32,e['name']
    model=dict(parent='minecraft:block/block',textures=textures,elements=[java_element(e,0,tw,th) for e in elements])
    display={
        'gui':dict(rotation=[25,225,0],translation=[0,0,0],scale=[0.7]*3),
        'ground':dict(rotation=[0,0,0],translation=[0,3,0],scale=[0.25]*3),
        'fixed':dict(rotation=[0,0,0],translation=[0,0,0],scale=[0.5]*3),
        'thirdperson_righthand':dict(rotation=[75,45,0],translation=[0,2.5,0],scale=[0.375]*3),
        'firstperson_righthand':dict(rotation=[0,45,0],translation=[0,0,0],scale=[0.4]*3)}
    write(assets/f'models/block/{ident}.json',model)
    write(assets/f'models/item/{ident}.json',dict(parent=f'archecraft:block/{ident}',display=display))
    write(assets/f'blockstates/{ident}.json',dict(variants={
        f'facing={facing}':dict(model=f'archecraft:block/{ident}',y=angle)
        for facing,angle in [('south',0),('west',90),('north',180),('east',270)]}))
    atlas.save(assets/f'textures/block/{ident}.png');atlas.save(here/f'{ident}.png')
    png=io.BytesIO();atlas.save(png,format='PNG')
    groups=[dict(name=g,origin=[8,0,8],uuid=str(uuid.uuid5(uuid.NAMESPACE_URL,ident+'/'+g)),
        children=[e['uuid'] for e in elements if e['_group']==g]) for g in dict.fromkeys(e['_group'] for e in elements)]
    write(here/f'{ident}.bbmodel',dict(meta=dict(format_version='4.10',model_format='java_block',box_uv=False),name=ident,
        resolution=dict(width=tw,height=th),elements=[{k:v for k,v in e.items() if not k.startswith('_')} for e in elements],
        outliner=groups,display=display,textures=[dict(name=ident+'.png',uuid=str(uuid.uuid5(uuid.NAMESPACE_URL,ident+'/texture')),
        id='0',namespace='archecraft',folder='block',width=tw,height=th,uv_width=tw,uv_height=th,mode='bitmap',saved=True,
        source='data:image/png;base64,'+base64.b64encode(png.getvalue()).decode())]))
    lines=['package com.redcookies.archecraft.workbench;','','import net.minecraft.core.Direction;',
        'import net.minecraft.world.level.block.Block;','import net.minecraft.world.phys.shapes.Shapes;',
        'import net.minecraft.world.phys.shapes.VoxelShape;','',f'// Generated by art/models/{ident}/build_model.py.',
        '// Coarse mass envelopes keep crosshair outlines inexpensive.',f'final class {shape_class} {{',
        '    static VoxelShape[] create() {','        VoxelShape[] shapes = new VoxelShape[4];','        double[][] boxes = {']
    assert len(boxes)<=4
    for b in boxes:
        assert 0<=b[0]<b[3]<=16 and 0<=b[2]<b[5]<=16 and 0<=b[1]<b[4]<=32
        lines.append('            {'+', '.join(str(v) for v in b)+'},')
    lines+=['        };','        for (Direction facing : Direction.Plane.HORIZONTAL) {',
        '            VoxelShape shape = Shapes.empty();','            for (double[] box : boxes) {',
        '                double x0=box[0], z0=box[2], x1=box[3], z1=box[5];',
        '                int turns = switch (facing) {case WEST -> 1; case NORTH -> 2; case EAST -> 3; default -> 0;};',
        '                for (int turn=0; turn<turns; turn++) {',
        '                    double nx0=16-z1, nz0=x0, nx1=16-z0, nz1=x1;',
        '                    x0=nx0; z0=nz0; x1=nx1; z1=nz1;','                }',
        '                shape=Shapes.or(shape, Block.box(x0,box[1],z0,x1,box[4],z1));','            }',
        '            shapes[facing.get2DDataValue()] = shape.optimize();','        }','        return shapes;','    }','}']
    (root/f'src/main/java/com/redcookies/archecraft/workbench/{shape_class}.java').write_text('\n'.join(lines)+'\n')
    preview=Image.new('RGB',(1400,655),(27,33,38))
    preview.paste(render(elements,atlas,32,center=(8,0,8),scale=24,baseline=450),(0,45))
    preview.paste(render(elements,atlas,212,center=(8,0,8),scale=24,baseline=450),(700,45))
    d=ImageDraw.Draw(preview);font=ImageFont.truetype('C:/Windows/Fonts/segoeuib.ttf',25)
    small=ImageFont.truetype('C:/Windows/Fonts/segoeui.ttf',16)
    d.text((30,15),title+' / ONE-BLOCK MODEL',font=font,fill=(226,226,215))
    d.text((30,620),'FRONT / 3-QUARTER',font=small,fill=(167,180,186))
    d.text((730,620),'REVERSE / 3-QUARTER',font=small,fill=(167,180,186))
    preview.save(here/f'{ident}_preview.png')
    print(f'Exported {len(elements)} cuboids, one block, editable project and {len(boxes)} gameplay boxes.')
