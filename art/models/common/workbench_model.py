"""Java/Blockbench exporter and preview renderer for two-space cuboid workbenches."""
from pathlib import Path
from PIL import Image, ImageDraw, ImageFont
import base64, io, json, math, uuid
import numpy as np

def write(path,data):
    path.parent.mkdir(parents=True,exist_ok=True)
    path.write_text(json.dumps(data,indent=2)+'\n',encoding='utf-8')

def export_two_block(here,root,ident,shape_class,elements,atlas,gameplay_boxes,title):
    assets=root/'src/main/resources/assets/archecraft'
    tw,th=atlas.size
    texture_name='archecraft:block/'+ident
    textures={'0':texture_name,'particle':texture_name}
    halves=[[],[]]
    for e in elements:
        r=native_rotation(e)
        lo,hi=e['from'],e['to']
        points=np.array([transform([x,y,z],r) for x in (lo[0],hi[0]) for y in (lo[1],hi[1]) for z in (lo[2],hi[2])])
        assert points[:,0].min()>=0 and points[:,0].max()<=32,e['name']
        assert points[:,2].min()>=0 and points[:,2].max()<=16,e['name']
        assert points[:,1].min()>=0 and points[:,1].max()<=32,e['name']
        for part in range(2):
            a,b=max(lo[0],part*16),min(hi[0],(part+1)*16)
            if a>=b:continue
            if r and r['axis']!='x':
                assert a==lo[0] and b==hi[0],'Cannot split this rotated cube: '+e['name']
            cut=json.loads(json.dumps(e));cut['from'][0]=a;cut['to'][0]=b
            for face in ['north','south','up','down']:
                uv=cut['faces'][face]['uv'];density=(uv[2]-uv[0])/(hi[0]-lo[0])
                offset=hi[0]-b if face=='north' else a-lo[0]
                uv[0]+=offset*density;uv[2]=uv[0]+(b-a)*density
            halves[part].append(java_element(cut,part*16,tw,th))
    for part,label in enumerate(['left','right']):
        write(assets/f'models/block/{ident}_{label}.json',dict(parent='minecraft:block/block',
              texture_size=[tw,th],textures=textures,elements=halves[part]))
    display={
     'gui':dict(rotation=[25,225,0],translation=[0,-1,0],scale=[0.46]*3),
     'ground':dict(rotation=[0,0,0],translation=[0,3,0],scale=[0.2]*3),
     'fixed':dict(rotation=[0,0,0],translation=[0,0,0],scale=[0.4]*3),
     'thirdperson_righthand':dict(rotation=[75,45,0],translation=[0,2.5,0],scale=[0.3]*3),
     'firstperson_righthand':dict(rotation=[0,45,0],translation=[0,0,0],scale=[0.35]*3)}
    write(assets/f'models/item/{ident}.json',dict(parent='minecraft:block/block',textures=textures,
          elements=[java_element(e,8,tw,th) for e in elements],display=display))
    # Authoring front is +Z (south). Rotate 180 degrees and exchange source halves
    # so state FACING points at the player without changing the placed pair's positions.
    write(assets/f'blockstates/{ident}.json',dict(variants={
        f'facing={facing},part={part}':dict(model=f'archecraft:block/{ident}_{"right" if part=="left" else "left"}',y=(angle+180)%360)
        for facing,angle in [('north',0),('east',90),('south',180),('west',270)] for part in ['left','right']}))
    atlas.save(assets/f'textures/block/{ident}.png');atlas.save(here/f'{ident}.png')
    png=io.BytesIO();atlas.save(png,format='PNG')
    groups=[dict(name=g,origin=[16,0,8],uuid=str(uuid.uuid5(uuid.NAMESPACE_URL,ident+'/'+g)),
            children=[e['uuid'] for e in elements if e['_group']==g]) for g in dict.fromkeys(e['_group'] for e in elements)]
    write(here/f'{ident}.bbmodel',dict(meta=dict(format_version='4.10',model_format='java_block',box_uv=False),
          name=ident,resolution=dict(width=tw,height=th),elements=[{k:v for k,v in e.items() if not k.startswith('_')} for e in elements],
          outliner=groups,display=display,textures=[dict(name=ident+'.png',uuid=str(uuid.uuid5(uuid.NAMESPACE_URL,texture_name)),id='0',
          namespace='archecraft',folder='block',width=tw,height=th,uv_width=tw,uv_height=th,mode='bitmap',saved=True,
          source='data:image/png;base64,'+base64.b64encode(png.getvalue()).decode())]))
    lines=['package com.redcookies.archecraft.workbench;','','import net.minecraft.core.Direction;',
     'import net.minecraft.world.level.block.Block;','import net.minecraft.world.phys.shapes.Shapes;',
     'import net.minecraft.world.phys.shapes.VoxelShape;','',f'// Generated by art/models/{ident}/build_model.py.',
     '// Deliberately simple: decorative props are not separate outline/collision geometry.',
     f'final class {shape_class} {{','    static VoxelShape[][] create() {',
     '        VoxelShape[][] shapes = new VoxelShape[2][4];','        double[][][] boxes = {']
    for boxes in gameplay_boxes:
        assert len(boxes)<=4
        lines.append('            {')
        for box in boxes:
            assert 0<=box[0]<box[3]<=16 and 0<=box[2]<box[5]<=16 and 0<=box[1]<box[4]<=32
            lines.append('                {'+', '.join(str(n) for n in box)+'},')
        lines.append('            },')
    lines+=['        };','        for (int part=0; part<2; part++) {',
     '            for (Direction facing : Direction.Plane.HORIZONTAL) {','                VoxelShape shape=Shapes.empty();',
     '                for (double[] box : boxes[part]) {','                    double x0=box[0], z0=box[2], x1=box[3], z1=box[5];',
     '                    for (int turn=0; turn < switch(facing) {case EAST -> 1; case SOUTH -> 2; case WEST -> 3; default -> 0;}; turn++) {',
     '                        double nx0=16-z1, nz0=x0, nx1=16-z0, nz1=x1;',
     '                        x0=nx0; z0=nz0; x1=nx1; z1=nz1;','                    }',
     '                    shape=Shapes.or(shape,Block.box(x0,box[1],z0,x1,box[4],z1));','                }',
     '                shapes[part][facing.get2DDataValue()]=shape.optimize();','            }','        }','        return shapes;','    }','}']
    (root/f'src/main/java/com/redcookies/archecraft/workbench/{shape_class}.java').write_text('\n'.join(lines)+'\n')
    preview=Image.new('RGB',(1400,655),(27,33,38))
    preview.paste(render(elements,atlas,32),(0,45));preview.paste(render(elements,atlas,212),(700,45))
    d=ImageDraw.Draw(preview)
    font=ImageFont.truetype('C:/Windows/Fonts/segoeuib.ttf',25);small=ImageFont.truetype('C:/Windows/Fonts/segoeui.ttf',16)
    d.text((30,15),title+' / two-block model',font=font,fill=(226,226,215))
    d.text((30,620),'FRONT / 3-QUARTER',font=small,fill=(167,180,186))
    d.text((730,620),'REVERSE / 3-QUARTER',font=small,fill=(167,180,186))
    preview.save(here/f'{ident}_preview.png')
    print(f'Exported {len(elements)} cuboids, two halves, embedded-texture project, and {sum(map(len,gameplay_boxes))} gameplay boxes.')

def java_element(e,shift,tw,th):
    lo,hi=e['from'].copy(),e['to'].copy();lo[0]-=shift;hi[0]-=shift
    result=dict(name=e['name'],**{'from':lo,'to':hi},faces={
        f:dict(uv=[v*16/(tw if i%2==0 else th) for i,v in enumerate(data['uv'])],texture='#0') for f,data in e['faces'].items()})
    r=native_rotation(e)
    if r:
        r['origin']=r['origin'].copy();r['origin'][0]-=shift;result['rotation']=r
    return result

def native_rotation(e):
    for i,angle in enumerate(e.get('rotation',[0,0,0])):
        if angle:return dict(angle=angle,axis='xyz'[i],origin=e['origin'],rescale=False)
    return None

def transform(v,r,normal=False):
    if not r:return np.array(v,dtype=float)
    origin=np.zeros(3) if normal else np.array(r['origin'],dtype=float)
    x,y,z=np.array(v,dtype=float)-origin
    a=math.radians(r['angle']);c,s=math.cos(a),math.sin(a)
    if r['axis']=='z':p=np.array([c*x-s*y,s*x+c*y,z])
    elif r['axis']=='y':p=np.array([c*x+s*z,y,-s*x+c*z])
    else:p=np.array([x,c*y-s*z,s*y+c*z])
    return p+origin


def render(elements,atlas,angle,center=(16,0,8),scale=16,baseline=485):
    """Depth-buffered orthographic render of these exact rotated textured elements."""
    yaw,pitch=math.radians(angle),math.radians(25)
    camera=np.array([math.sin(yaw)*math.cos(pitch),math.sin(pitch),math.cos(yaw)*math.cos(pitch)])
    def project(v):
        x,y,z=v-center;h=x*math.cos(yaw)-z*math.sin(yaw);f=x*math.sin(yaw)+z*math.cos(yaw)
        return [350+h*scale,baseline-y*math.cos(pitch)*scale+f*math.sin(pitch)*scale,f*math.cos(pitch)+y*math.sin(pitch)]
    canvas=Image.new('RGB',(700,590),(27,33,38))
    ImageDraw.Draw(canvas).ellipse((75,410,625,555),fill=(19,24,28))
    pixels=np.array(canvas);depths=np.full((590,700),-np.inf);texture=np.array(atlas)[:,:,:3]
    def triangle(points,uv,shade):
        points=np.array(points)
        x0=max(0,int(math.floor(points[:,0].min())));x1=min(700,int(math.ceil(points[:,0].max())))
        y0=max(0,int(math.floor(points[:,1].min())));y1=min(590,int(math.ceil(points[:,1].max())))
        if x1<=x0 or y1<=y0:return
        a,b,c=points;divisor=(b[1]-c[1])*(a[0]-c[0])+(c[0]-b[0])*(a[1]-c[1])
        if abs(divisor)<0.001:return
        xx,yy=np.meshgrid(np.arange(x0,x1)+0.5,np.arange(y0,y1)+0.5)
        wa=((b[1]-c[1])*(xx-c[0])+(c[0]-b[0])*(yy-c[1]))/divisor
        wb=((c[1]-a[1])*(xx-c[0])+(a[0]-c[0])*(yy-c[1]))/divisor
        wc=1-wa-wb;zz=wa*a[2]+wb*b[2]+wc*c[2];region=depths[y0:y1,x0:x1]
        mask=(wa>=-1e-8)&(wb>=-1e-8)&(wc>=-1e-8)&(zz>region);uv=np.array(uv)
        u=np.clip(np.floor(wa*uv[0,0]+wb*uv[1,0]+wc*uv[2,0]).astype(int),0,texture.shape[1]-1)
        v=np.clip(np.floor(wa*uv[0,1]+wb*uv[1,1]+wc*uv[2,1]).astype(int),0,texture.shape[0]-1)
        color=np.clip(texture[v,u]*shade,0,255).astype(np.uint8)
        pixels[y0:y1,x0:x1][mask]=color[mask];region[mask]=zz[mask]
    for e in elements:
        x0,y0,z0=e['from'];x1,y1,z1=e['to'];r=native_rotation(e)
        surfaces={
         'north':([(x1,y1,z0),(x0,y1,z0),(x0,y0,z0),(x1,y0,z0)],(0,0,-1)),
         'south':([(x0,y1,z1),(x1,y1,z1),(x1,y0,z1),(x0,y0,z1)],(0,0,1)),
         'east': ([(x1,y1,z1),(x1,y1,z0),(x1,y0,z0),(x1,y0,z1)],(1,0,0)),
         'west': ([(x0,y1,z0),(x0,y1,z1),(x0,y0,z1),(x0,y0,z0)],(-1,0,0)),
         'up': ([(x0,y1,z0),(x1,y1,z0),(x1,y1,z1),(x0,y1,z1)],(0,1,0)),
         'down': ([(x0,y0,z1),(x1,y0,z1),(x1,y0,z0),(x0,y0,z0)],(0,-1,0))}
        for face,(verts,normal) in surfaces.items():
            n=transform(normal,r,normal=True)
            if np.dot(n,camera)<=0:continue
            points=[project(transform(v,r)) for v in verts]
            u0,v0,u1,v1=e['faces'][face]['uv'];uv=[(u0,v0),(u1,v0),(u1,v1),(u0,v1)]
            shade=0.76+max(0,n[1])*0.28+max(0,n[2])*0.1+max(0,-n[0])*0.07
            for inds in [(0,1,2),(0,2,3)]:triangle([points[i] for i in inds],[uv[i] for i in inds],shade)
    return Image.fromarray(pixels)

